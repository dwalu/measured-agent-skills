#!/usr/bin/env node
// Validator + generator for the Markdown work-tracking system.
//
// Dependency-free (pure Node ESM) so git hooks run before `npm install` ever
// has — that property is load-bearing, not incidental: the first commit in a
// repo is the one that adds the toolchain, and a tracking gate that needs the
// toolchain cannot gate it.
//
// Usage:
//   node scripts/validate-tracking.mjs                  validate (non-zero exit on error)
//   node scripts/validate-tracking.mjs --write          regenerate MASTER + QUEUE, then validate
//   node scripts/validate-tracking.mjs --commit-msg F   validate a commit message's task trailer
//   node scripts/validate-tracking.mjs --next [n]       print the head of the queue
//   node scripts/validate-tracking.mjs --json           machine-readable state (for agents/tools)
//   node scripts/validate-tracking.mjs --new-task <featureId> [opts]
//   node scripts/validate-tracking.mjs --renumber [--apply]
//
// Hierarchy: Spec -> Flow (F01) -> Feature (F01.2) -> Design/Impl task (F01.2-D1 / F01.2-I1)
// Conventions the parser expects live in <dir>/README.md.
//
// Configure with `tracking.config.json` at the repo root (all keys optional).

import {
  readdirSync,
  readFileSync,
  writeFileSync,
  existsSync,
  statSync,
} from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// ---- root + config ---------------------------------------------------------

function repoRoot() {
  try {
    return execFileSync('git', ['rev-parse', '--show-toplevel'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim();
  } catch {
    // Not a git checkout: fall back to the directory above this script, which
    // is where it lives once installed (<root>/scripts/validate-tracking.mjs).
    return resolve(dirname(fileURLToPath(import.meta.url)), '..');
  }
}

const ROOT = repoRoot();

const DEFAULTS = {
  /** Directory holding MASTER.md, QUEUE.md, README.md and flows/. */
  dir: 'plans/tracking',
  /** Letter that opens every id. Two-or-more digits follow it. */
  idPrefix: 'F',
  /** Written into lines generated by --new-task. */
  defaultOwner: null,
  /** Commit-message trailer key: `Task: F01.2-I1`. */
  commitTrailer: 'Task',
  /**
   * Promote the two advisory checks to hard errors. Both default OFF because
   * they are migration-hostile — a repo adopting this mid-flight would fail
   * every commit until its whole backlog was annotated. A greenfield repo
   * should turn both ON in its first commit, while the cost is zero.
   */
  strict: { owner: false, rank: false },
  /** `requiredSections: [4,5,6]` makes MASTER.md report spec coverage. */
  spec: { requiredSections: [] },
  citations: {
    enabled: true,
    /** Code that may name a task id. Missing entries are skipped silently. */
    source: ['src', 'packages', 'apps', 'lib', 'e2e', 'test', 'tests'],
    sourceExtensions: [
      '.ts', '.tsx', '.js', '.jsx', '.mjs', '.sql', '.prisma',
      '.py', '.go', '.rs', '.rb', '.java', '.kt', '.cs', '.php',
    ],
    /** Path prefixes exempt from the promise check (e.g. immutable migrations). */
    sourceExclude: [],
    /** Prose that may cite an id or a TODO number. */
    docs: ['docs', 'plans', '.claude', '*.md'],
    /**
     * Prose exempt from the citation check. Defaults to the tracking README,
     * which is not optional: that document *specifies the id grammar*, so its
     * worked examples are necessarily fictional ids. Without this the scaffold
     * fails on the repo's very first commit.
     */
    docsExclude: null,
    promiseVerbs: ['drops', 'retires', 'removes', 'replaces', 'contracts', 'dies'],
    /** `{ "TODO-40": "burned on purpose — see README" }` */
    deadRefs: {},
  },
};

function loadConfig() {
  const flagIdx = process.argv.indexOf('--config');
  const path = flagIdx > -1 ? process.argv[flagIdx + 1] : join(ROOT, 'tracking.config.json');
  if (!existsSync(path)) return structuredClone(DEFAULTS);
  let raw;
  try {
    raw = JSON.parse(readFileSync(path, 'utf8'));
  } catch (e) {
    console.error(`❌ ${path}: not valid JSON — ${e.message}`);
    process.exit(2);
  }
  const merged = structuredClone(DEFAULTS);
  for (const [k, v] of Object.entries(raw)) {
    merged[k] =
      v && typeof v === 'object' && !Array.isArray(v) && merged[k] && typeof merged[k] === 'object'
        ? { ...merged[k], ...v }
        : v;
  }
  return merged;
}

const cfg = loadConfig();
cfg.citations.docsExclude ??= [`${cfg.dir.replace(/\/+$/, '')}/README.md`];

const TRACKING_DIR = join(ROOT, cfg.dir);
const FLOWS_DIR = join(TRACKING_DIR, 'flows');
const MASTER = join(TRACKING_DIR, 'MASTER.md');
const QUEUE = join(TRACKING_DIR, 'QUEUE.md');
/** Repo-relative, for messages and for the links inside generated tables. */
const REL = cfg.dir.replace(/\/+$/, '');

const esc = (s) => String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const P = esc(cfg.idPrefix);

const RE = {
  flowHead: new RegExp(`^#\\s+(${P}\\d{2,})\\s+[—-]\\s+(.+?)\\s*$`),
  featureHead: new RegExp(`^##\\s+(${P}\\d{2,}\\.\\d+)\\s+[—-]\\s+(.+?)\\s*$`),
  section: /^###\s+(Design|Implementation)\s*$/,
  field: /^-\s+\*\*(Spec|Phase|Status|PR|Owner|Rank):\*\*\s*(.+?)\s*$/,
  task: /^-\s+\[([ x])\]\s+`([^`]+)`\s+(.+?)\s*$/,
  taskId: new RegExp(`^${P}\\d{2,}\\.\\d+-[DI]\\d+$`),
  taskRef: new RegExp(`${P}\\d{2,}\\.\\d+-[DI]\\d+`, 'g'),
  todoRef: /TODO-\d+/g,
};

// Status vocabulary — the emoji IS the canonical status marker.
const STATUS = {
  '⬜': 'todo',
  '🟨': 'in_progress',
  '🟦': 'in_review',
  '✅': 'done',
  '⛔': 'blocked',
  '⏸️': 'deferred',
};
const EMOJI = Object.fromEntries(Object.entries(STATUS).map(([e, s]) => [s, e]));

const errors = [];
const warnings = [];
const err = (m) => errors.push(m);
const warn = (m) => warnings.push(m);
/** Started-or-finished tasks with no owner; summarized once at the end. */
const ownerless = [];
/** Open tasks with no rank at any level; summarized once at the end. */
const unranked = [];

function detectStatus(text) {
  for (const [emoji, name] of Object.entries(STATUS)) {
    if (text.includes(emoji)) return name;
  }
  return null;
}
function specSections(text) {
  return [...text.matchAll(/§\s*(\d+)/g)].map((m) => Number(m[1]));
}

// ---- parse -----------------------------------------------------------------

function parseFlowFile(file, raw) {
  const lines = raw.split(/\r?\n/);
  const flow = { file, tasks: [], features: [], spec: null, phase: null, status: null };
  let feature = null;
  let section = null; // 'Design' | 'Implementation'

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    const at = `${file}:${i + 1}`;

    let m;
    if ((m = line.match(RE.flowHead))) {
      flow.id = m[1];
      flow.title = m[2].trim();
      flow.line = i + 1;
      feature = null;
      section = null;
    } else if ((m = line.match(RE.featureHead))) {
      feature = {
        id: m[1], title: m[2].trim(), tasks: [],
        spec: null, status: null, pr: null, at, line: i + 1,
      };
      flow.features.push(feature);
      section = null;
    } else if ((m = line.match(RE.section))) {
      section = m[1];
      if (feature) feature[`${section.toLowerCase()}Line`] = i + 1;
    } else if ((m = line.match(RE.field))) {
      const key = m[1].toLowerCase();
      const val = m[2].trim();
      const target = feature || flow;
      if (key === 'status') target.status = { raw: val, name: detectStatus(val), at };
      else target[key] = val;
      if (key === 'rank') target.rankLine = i + 1;
    } else if ((m = line.match(RE.task))) {
      const checked = m[1] === 'x';
      const id = m[2].trim();
      const rest = m[3];
      const task = {
        id, checked, rest, at, section, line: i + 1,
        status: detectStatus(rest),
        pr: (rest.match(/PR\s*#(\d+)/i) || rest.match(/#(\d+)/) || [])[1] || null,
        blockedReason: (rest.match(/\(blocked:\s*([^)]+)\)/i) || [])[1] || null,
        // Inline `**Owner:** <name>` on the task, overriding the feature's.
        owner: (rest.match(/\*\*Owner:\*\*\s*([^·|—]+)/) || [])[1]?.trim() || null,
        // Bold is OWNERSHIP; plain is CITATION. A task owns the number written
        // in bold immediately after its id, and nothing else. The unanchored
        // form this replaced took the first bold `TODO-n` anywhere in the line,
        // so a task citing someone else's number parsed as owning it — a false
        // duplicate the moment uniqueness is enforced.
        todo: (rest.match(/^\*\*(TODO-\d+)\*\*(?=\s*·)/) || [])[1] || null,
        // Any bold TODO, used only to catch one written in the wrong place —
        // otherwise a misplaced number silently reads as "this task has none".
        todoLoose: (rest.match(/\*\*(TODO-\d+)\*\*/) || [])[1] || null,
        // Order. Inherited from feature, then flow, when absent — see
        // effectiveRank. Deliberately NOT `#\d+`: `pr` above falls back to a
        // bare `/#(\d+)/`, so a `#`-prefixed rank would satisfy the "🟦/✅ needs
        // a PR link" rule using its own rank number.
        rank: (rest.match(/\*\*Rank:\*\*\s*(\d+)\b/) || [])[1] || null,
        // Distinguishes "no rank" from "a rank I could not parse".
        rankRaw: /\*\*Rank:\*\*/.test(rest),
        feature,
      };
      if (!feature) err(`${at}: task \`${id}\` is not under a feature`);
      else if (!section) err(`${at}: task \`${id}\` is not under a ### Design or ### Implementation heading`);
      else feature.tasks.push(task);
      flow.tasks.push(task);
    }
  }
  // Back-link so a task can resolve its inherited rank without a second lookup.
  for (const t of flow.tasks) t.flow = flow;
  for (const f of flow.features) f.flow = flow;
  return flow;
}

/**
 * Rank precedence: inline task rank → feature rank → flow rank → unranked.
 *
 * Verbatim the shape Owner already uses, so it is one pattern serving two
 * fields rather than a second concept to learn. Feature-level is the DEFAULT
 * case, not the exception: a feature is usually wanted at one point in the
 * queue as a unit, with the odd task pulled out of line.
 */
function effectiveRank(t) {
  const raw = t.rank ?? t.feature?.rank ?? t.flow?.rank ?? null;
  const n = raw === null ? NaN : Number(raw);
  // A malformed rank is reported once, where it is written. Returning null
  // rather than NaN stops one bad feature heading from also reporting every
  // task that inherits it — nine errors for one typo, none naming the typo.
  return Number.isFinite(n) ? n : null;
}

/** A flow- or feature-level `- **Rank:** <n>` must be a plain 1–9999 integer. */
function checkRankValue(raw, what) {
  if (raw == null) return;
  if (!/^\d+$/.test(String(raw).trim())) {
    err(`${what} has a malformed '- **Rank:**' (\`${raw}\`) — a plain positive integer, no '#'`);
    return;
  }
  const n = Number(raw);
  if (n < 1 || n > 9999) err(`${what} has rank ${n} outside the range 1–9999`);
}

// ---- validate --------------------------------------------------------------

function validateFlow(flow) {
  const base = flow.file;
  if (!flow.id) { err(`${base}: missing '# ${cfg.idPrefix}## — Title' header`); return; }
  if (!flow.spec) err(`${base}: flow ${flow.id} missing '- **Spec:**'`);
  if (!flow.status || !flow.status.name) {
    err(`${base}: flow ${flow.id} missing a valid '- **Status:**' (need one of ${Object.keys(EMOJI).join('/')})`);
  }
  checkRankValue(flow.rank, `${base}: flow ${flow.id}`);

  for (const f of flow.features) {
    if (!f.id.startsWith(flow.id + '.')) err(`${f.at}: feature ${f.id} is not a child of ${flow.id}`);
    checkRankValue(f.rank, `${f.at}: feature ${f.id}`);
    if (!f.spec) err(`${f.at}: feature ${f.id} missing '- **Spec:**'`);
    if (!f.status || !f.status.name) err(`${f.at}: feature ${f.id} missing a valid '- **Status:**'`);
    const deferred = f.status && f.status.name === 'deferred';
    if (!deferred && f.tasks.length === 0) {
      err(`${f.at}: feature ${f.id} has no tasks (only ⏸️ deferred features may be empty)`);
    }
    if (f.status && f.status.name === 'done') {
      const undone = f.tasks.filter((t) => t.status !== 'done');
      if (f.tasks.length === 0 || undone.length) {
        err(`${f.at}: feature ${f.id} marked ✅ but ${undone.length} task(s) are not ✅`);
      }
    }
    for (const t of f.tasks) validateTask(t, f);
  }
  if (flow.status && flow.status.name === 'done') {
    const undone = flow.features.filter((f) => !f.status || f.status.name !== 'done');
    if (flow.features.length === 0 || undone.length) {
      err(`${base}: flow ${flow.id} marked ✅ but ${undone.length} feature(s) are not ✅`);
    }
  }
}

function validateTask(t, feature) {
  if (!RE.taskId.test(t.id)) {
    err(`${t.at}: task id \`${t.id}\` is malformed (expected e.g. ${cfg.idPrefix}01.2-I1)`);
  }
  if (!t.id.startsWith(feature.id + '-')) err(`${t.at}: task \`${t.id}\` does not belong to feature ${feature.id}`);
  if (!t.status) { err(`${t.at}: task \`${t.id}\` has no status emoji`); return; }
  if (t.checked && t.status !== 'done') {
    err(`${t.at}: task \`${t.id}\` checkbox [x] but status is ${t.status} (checkbox and ✅ must agree)`);
  }
  if (!t.checked && t.status === 'done') err(`${t.at}: task \`${t.id}\` is ✅ done but checkbox is [ ] (mark [x])`);
  if ((t.status === 'in_review' || t.status === 'done') && !t.pr) {
    err(`${t.at}: task \`${t.id}\` is ${t.status} but has no 'PR #<n>' link`);
  }
  if (t.status === 'blocked' && !t.blockedReason) {
    err(`${t.at}: task \`${t.id}\` is ⛔ blocked but has no '(blocked: reason)'`);
  }

  // Ownership. Unstarted work (⬜ todo, ⏸️ deferred) is exempt: the backlog is
  // allowed to be unassigned, and "unassigned work does not start" is precisely
  // the line that draws. Anything in flight or finished should say whose it was.
  // Collected into ONE summary line rather than one per task — a hundred
  // warnings a run is how a warning channel becomes something people scroll past.
  const needsOwner = t.status && !['todo', 'deferred'].includes(t.status);
  if (needsOwner && !t.owner && !feature.owner) ownerless.push(t);

  // A bold TODO number may sit ONLY immediately after the task id, because bold
  // is how a task claims a number. Written anywhere else it is a citation and
  // must be plain. Without this the anchored parse above would silently read a
  // misplaced number as "no number" — the same class of quiet wrongness the
  // anchoring exists to fix, so the placement is enforced, not assumed.
  if (t.todoLoose && !t.todo) {
    err(
      `${t.at}: task \`${t.id}\` has a bold **${t.todoLoose}** that is not immediately after the task id — ` +
        `a task's own number goes first ("\`${t.id}\` **${t.todoLoose}** · …"), and a number you are only citing is written plain, without asterisks`,
    );
  }

  // `**Rank:**` present but unparseable. Reported rather than ignored: an
  // unparseable rank reads as "unranked", so the task quietly falls to the
  // bottom of the queue while its line looks ranked.
  if (t.rankRaw && !t.rank) {
    err(`${t.at}: task \`${t.id}\` has a malformed **Rank:** — a plain positive integer with no '#' (a '#' would be read as a PR link)`);
  }
  // The task's OWN rank only — an inherited one is validated at its source.
  if (t.rank !== null) checkRankValue(t.rank, `${t.at}: task \`${t.id}\``);

  // Unranked is a LEGAL state meaning "backlog, order not yet decided": it
  // sorts last in the queue and is counted once so it cannot grow unnoticed.
  // Requiring a global priority judgement at the moment of filing would tax
  // exactly the behaviour this system exists to make cheap — filing discovered
  // work instead of absorbing it. Done and deferred are exempt.
  const needsRank = t.status && !['done', 'deferred'].includes(t.status);
  if (needsRank && effectiveRank(t) === null) unranked.push(t);
}

function loadFlows() {
  if (!existsSync(FLOWS_DIR)) {
    err(`missing directory ${REL}/flows — run the work-tracking skill's init to scaffold it`);
    return [];
  }
  const files = readdirSync(FLOWS_DIR).filter((f) => f.endsWith('.md')).sort();
  const flows = files.map((f) =>
    parseFlowFile(`${REL}/flows/${f}`, readFileSync(join(FLOWS_DIR, f), 'utf8')),
  );

  // Global uniqueness of every id, and of every TODO number.
  //
  // TODO numbers share this namespace deliberately — a `TODO-49` key cannot
  // collide with an `F02.1-I9` key, and one map means one error message. The
  // number is an IDENTITY: allocated once, never reused, cited in commit
  // messages and design docs that no tool can re-point. This closes the one
  // race the scheme has: two concurrent PRs both taking the next free number.
  // Caught at PR time the loser can still renumber safely — nothing cites it yet.
  const seen = new Map();
  const claim = (id, at) => {
    if (seen.has(id)) err(`${at}: duplicate id or TODO number \`${id}\` (also at ${seen.get(id)})`);
    else seen.set(id, at);
  };
  for (const fl of flows) {
    if (fl.id) claim(fl.id, fl.file);
    for (const f of fl.features) claim(f.id, f.at);
    for (const t of fl.tasks) {
      claim(t.id, t.at);
      if (t.todo) claim(t.todo, t.at);
    }
  }
  return flows;
}

// ---- the rollup ------------------------------------------------------------

function rollupTable(flows) {
  const rows = flows
    .filter((f) => f.id)
    .sort((a, b) => a.id.localeCompare(b.id))
    .map((f) => {
      const total = f.tasks.length;
      const done = f.tasks.filter((t) => t.status === 'done').length;
      const st = f.status && f.status.name ? EMOJI[f.status.name] : '?';
      // Link the id, so this generated row also carries the navigation a
      // hand-maintained bullet list used to — and which silently lost a flow.
      const file = f.file.replace(`${REL}/`, '');
      return `| [${f.id}](${file}) | ${f.title || ''} | ${f.spec || ''} | ${f.phase || ''} | ${done}/${total} | ${st} |`;
    });
  return [
    '| Flow | Title | Spec | Phase | Progress | Status |',
    '|------|-------|------|-------|----------|--------|',
    ...rows,
  ].join('\n');
}

function coverage(flows) {
  const required = cfg.spec?.requiredSections ?? [];
  if (!required.length) return null;
  const covered = new Set();
  for (const fl of flows) {
    specSections(fl.spec || '').forEach((s) => covered.add(s));
    for (const f of fl.features) specSections(f.spec || '').forEach((s) => covered.add(s));
  }
  return { covered: [...covered].sort((a, b) => a - b), missing: required.filter((s) => !covered.has(s)) };
}

function masterBlock(flows) {
  const cov = coverage(flows);
  const note = !cov
    ? null
    : cov.missing.length
      ? `> ⚠️ Uncovered required spec sections: ${cov.missing.map((s) => '§' + s).join(', ')}`
      : `> ✅ All required spec sections are covered by at least one flow.`;
  return [rollupTable(flows), ...(note ? ['', note] : [])].join('\n');
}

// ---- the queue -------------------------------------------------------------
// The generated ordering. Hand-maintained order is what this replaces: the same
// sequence copied by hand into several documents drifts in all of them, and the
// drift is invisible because nobody diffs prose against prose.

/** One-line human label for a task: its first bold run, else its feature title. */
function taskLabel(t) {
  let s = t.rest;
  // Drop the structured prefix fields so the label is prose, not metadata.
  s = s.replace(/^\*\*TODO-\d+\*\*\s*·\s*/, '');
  s = s.replace(/\*\*Rank:\*\*\s*\d+\s*·\s*/, '');
  s = s.replace(/\*\*Owner:\*\*[^·]*·\s*/, '');
  s = s.trim();
  // Two shapes exist. Most tasks open with a bold one-line title; others open
  // with plain prose and put the detail after an em dash. Anchoring to the
  // START of the remaining text keeps a bold phrase buried mid-sentence from
  // being mistaken for the title.
  const lead = s.match(/^\*\*(.+?)\*\*/);
  let label = lead ? lead[1] : s.split(/\s+—\s+|\s+\(/)[0];
  if (!label.trim() || /^\w+:$/.test(label.trim())) label = t.feature?.title ?? t.id;
  for (const emoji of Object.keys(STATUS)) label = label.split(emoji).join('');
  // A pipe would break the table cell it sits in.
  label = label.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
  return label.length > 90 ? label.slice(0, 89).trimEnd() + '…' : label;
}

/**
 * Open tasks in queue order.
 *
 * Ties are LEGAL and broken deterministically by (rank, file, line). Requiring
 * unique ranks would re-create, one layer up, the very race this scheme closes:
 * two PRs both inserting "just before Stage B" both pick 150.
 */
function queueRows(flows) {
  const open = [];
  for (const fl of flows) {
    for (const t of fl.tasks) {
      if (t.status === 'done' || t.status === 'deferred') continue;
      open.push({ t, rank: effectiveRank(t), file: t.flow?.file ?? '', line: t.line ?? 0 });
    }
  }
  open.sort((a, b) => {
    const ar = a.rank ?? Infinity;
    const br = b.rank ?? Infinity;
    if (ar !== br) return ar - br;
    if (a.file !== b.file) return a.file.localeCompare(b.file);
    return a.line - b.line;
  });
  return open;
}

function queueSection(rows) {
  if (!rows.length) return ['| — | — | — | — | — |'];
  return rows.map(({ t, rank }) => {
    const file = (t.flow?.file ?? '').replace(`${REL}/`, '../');
    return `| ${rank ?? '—'} | [\`${t.id}\`](${file}) | ${t.todo ?? '—'} | ${EMOJI[t.status] ?? '?'} | ${taskLabel(t)} |`;
  });
}

function queueTable(flows) {
  const rows = queueRows(flows);
  const blocked = rows.filter((r) => r.t.status === 'blocked');
  const ranked = rows.filter((r) => r.t.status !== 'blocked' && r.rank !== null);
  const none = rows.filter((r) => r.t.status !== 'blocked' && r.rank === null);
  const head = ['| Rank | Task | TODO | Status | What |', '|------|------|------|--------|------|'];

  const out = [
    `**${ranked.length} ranked · ${none.length} unranked · ${blocked.length} blocked.** Deferred (⏸️) and done (✅) tasks are not in the queue.`,
    '',
  ];
  out.push('## Next', '', ...head, ...queueSection(ranked));
  out.push(
    '', '## Unranked backlog', '',
    '_Legal, and means "order not decided yet" — these sort last. Give one a `**Rank:**` when it earns a place._',
    '', ...head, ...queueSection(none),
  );
  out.push(
    '', '## Blocked', '',
    '_Ranked, but not startable. Shown separately so the queue never implies one of these is next._',
    '',
  );
  out.push('| Rank | Task | TODO | Blocked on |', '|------|------|------|------------|');
  out.push(
    ...(blocked.length
      ? blocked.map(({ t, rank }) => {
          const file = (t.flow?.file ?? '').replace(`${REL}/`, '../');
          return `| ${rank ?? '—'} | [\`${t.id}\`](${file}) | ${t.todo ?? '—'} | ${(t.blockedReason ?? '').replace(/\|/g, '\\|')} |`;
        })
      : ['| — | — | — | — |']),
  );
  return out.join('\n');
}

// ---- generated-block plumbing ---------------------------------------------

const MARK = (name, path) => ({
  start: `<!-- ${name}:START (auto-generated by ${path} --write; do not edit by hand) -->`,
  re: new RegExp(`^<!-- ${name}:START[\\s\\S]*?^<!-- ${name}:END -->`, 'm'),
  readRe: new RegExp(`^<!-- ${name}:START[\\s\\S]*?\\n([\\s\\S]*?)\\n(?=<!-- ${name}:END -->$)`, 'm'),
  end: `<!-- ${name}:END -->`,
});

const SCRIPT_REL = 'node scripts/validate-tracking.mjs';

function writeBlock(file, name, body) {
  if (!existsSync(file)) { err(`missing ${file}`); return; }
  const raw = readFileSync(file, 'utf8');
  const m = MARK(name, SCRIPT_REL);
  if (!m.re.test(raw)) { err(`${file}: missing <!-- ${name}:START --> ... <!-- ${name}:END --> markers`); return; }
  writeFileSync(file, raw.replace(m.re, `${m.start}\n${body}\n${m.end}`));
}

function checkBlockFresh(file, name, body, label) {
  if (!existsSync(file)) { err(`missing ${file}`); return; }
  const raw = readFileSync(file, 'utf8');
  const m = MARK(name, SCRIPT_REL);
  const found = raw.match(m.readRe);
  if (!found) { err(`${file}: missing ${name} markers`); return; }
  if (found[1] !== body) err(`${file}: ${label} is stale — run: ${SCRIPT_REL} --write`);
}

// ---- citation + promise integrity -----------------------------------------
// Code comments make promises about future increments ("F17.4-I1 retires this
// table"). Those promises rot silently: the increment ships, the comment stays,
// and the next reader believes it. These checks make finding them mechanical.

function gitFiles(...paths) {
  const out = execFileSync('git', ['ls-files', '-z', ...paths], {
    cwd: ROOT,
    encoding: 'utf8',
    maxBuffer: 64 * 1024 * 1024,
  });
  return out.split('\0').filter(Boolean);
}

/** Config paths that do not exist are dropped — `git ls-files` errors on them. */
function presentPaths(paths) {
  return paths.filter((p) => p.includes('*') || existsSync(join(ROOT, p)));
}

function sourceFiles() {
  const roots = presentPaths(cfg.citations.source);
  if (!roots.length) return [];
  return gitFiles(...roots)
    .filter((f) => cfg.citations.sourceExtensions.some((e) => f.endsWith(e)))
    .filter((f) => !cfg.citations.sourceExclude.some((p) => f.startsWith(p)));
}

// Prose gets the id-existence check but NOT the promise check. Documentation is
// written in the future tense on purpose ("F02.1-I10 replaces the stub"), so the
// heuristic that reads well against a code comment would be noise here.
function docFiles() {
  const roots = presentPaths(cfg.citations.docs);
  if (!roots.length) return [];
  return gitFiles(...roots)
    .filter((f) => f.endsWith('.md'))
    .filter((f) => !cfg.citations.docsExclude.some((p) => f === p || f.startsWith(p.replace(/\/?$/, '/'))));
}

function taskIndex(flows) {
  const idx = new Map();
  for (const fl of flows) for (const t of fl.tasks) idx.set(t.id, t);
  return idx;
}

function checkPromises(flows) {
  if (!cfg.citations.enabled) return;
  const idx = taskIndex(flows);
  const deadRefs = new Map(Object.entries(cfg.citations.deadRefs ?? {}));

  // A promise is the task id followed *closely* by a future-tense verb. The
  // 25-character window is load-bearing: a real promise reads "F17.4-I1 drops
  // it" (1 char), while prose like "(F01.3-I3): student A takes the seat, B
  // waitlists, A drops → B promoted" is a student dropping a *course*, 43
  // characters away. Widen this and that line becomes a false positive.
  const PROMISE = new RegExp(
    `(${P}\\d{2,}\\.\\d+-[DI]\\d+)[^.;]{0,25}\\b(${cfg.citations.promiseVerbs.map(esc).join('|')})\\b`,
    'g',
  );

  let files = [];
  let docs = [];
  try {
    files = sourceFiles();
  } catch {
    // Not a git checkout (or git unavailable) — skip rather than fail the run.
    warn('promise checks skipped: could not list git-tracked files');
    return;
  }
  try {
    docs = docFiles();
  } catch {
    warn('doc citation checks skipped: could not list git-tracked files');
  }

  // Every TODO number cited anywhere must resolve to a task that defines it.
  // This is the other half of making TODO a stable identity: a number is only
  // worth citing if the citation can be followed.
  const todos = new Map();
  for (const fl of flows) for (const t of fl.tasks) if (t.todo) todos.set(t.todo, t.id);

  for (const file of docs) {
    let raw;
    try { raw = readFileSync(join(ROOT, file), 'utf8'); } catch { continue; }
    raw.split(/\r?\n/).forEach((line, i) => {
      const at = `${file}:${i + 1}`;
      for (const ref of [...(line.match(RE.taskRef) ?? []), ...(line.match(RE.todoRef) ?? [])]) {
        if (idx.has(ref) || todos.has(ref) || deadRefs.has(ref)) continue;
        err(
          `${at} cites ${ref}, which nothing defines. Ids and TODO numbers are never reused, so a citation that does not resolve is a typo — ` +
            `unless the reference is dead on purpose, in which case add it to citations.deadRefs in tracking.config.json with the reason.`,
        );
      }
    });
  }

  for (const file of files) {
    let raw;
    try { raw = readFileSync(join(ROOT, file), 'utf8'); } catch { continue; } // deleted-but-tracked mid-rebase
    raw.split(/\r?\n/).forEach((line, i) => {
      const at = `${file}:${i + 1}`;

      // 1. Every task id named in code must actually exist.
      for (const id of line.match(RE.taskRef) ?? []) {
        if (!idx.has(id) && !deadRefs.has(id)) {
          err(`${at} references task ${id}, which does not exist in the tracking files — fix the id, or open the task it is promising`);
        }
      }

      // 2. A promise must not name a task that is already done: either it was
      //    kept and the comment is stale, or it was quietly dropped and nobody
      //    owns it. Both need a human; the fix differs.
      for (const m of line.matchAll(PROMISE)) {
        if (idx.get(m[1])?.status === 'done') {
          err(
            `${at} still promises that ${m[1]} "${m[2]}" something, but ${m[1]} is done — ` +
              `if it was kept, put the comment in the past tense; if it was dropped, open a task that owns it`,
          );
        }
      }
    });
  }
}

// ---- commit-msg mode -------------------------------------------------------

function commitMsgMode(path, flows) {
  const msg = readFileSync(path, 'utf8');
  const subject = msg.split(/\r?\n/).find((l) => l.trim() && !l.startsWith('#')) || '';
  if (/^Merge /.test(subject) || /^Revert/.test(subject) || /\[skip-task\]/.test(msg)) return; // exempt
  const key = esc(cfg.commitTrailer);
  const trailer = msg.match(new RegExp(`^${key}:\\s*(${P}\\d{2,}\\.\\d+-[DI]\\d+)\\s*$`, 'm'));
  if (!trailer) {
    err(
      `commit message must include a trailer line: "${cfg.commitTrailer}: <id>" ` +
        `(e.g. ${cfg.commitTrailer}: ${cfg.idPrefix}01.2-I1), or "[skip-task]" for non-task commits`,
    );
    return;
  }
  const id = trailer[1];
  const task = taskIndex(flows).get(id);
  if (!task) err(`commit references ${cfg.commitTrailer}: ${id}, which does not exist in the tracking files`);
  else if (task.status === 'done' || task.status === 'deferred') {
    err(`commit references ${cfg.commitTrailer}: ${id}, which is already ${task.status} — reopen it or reference an active task`);
  }
}

// ---- --new-task ------------------------------------------------------------
// Allocating a TODO number by hand means reading the whole tree and hoping. The
// number is an identity that can never be reused, so a mis-allocation is
// permanent; this makes the allocation mechanical, and can insert the line.

function nextTodo(flows) {
  let max = 0;
  for (const fl of flows) for (const t of fl.tasks) {
    if (t.todo) max = Math.max(max, Number(t.todo.slice(5)));
  }
  // Burned numbers count: DEAD_REFS entries are numbers spent on nothing, and
  // reissuing one would resurrect a citation pointing somewhere else.
  for (const ref of Object.keys(cfg.citations.deadRefs ?? {})) {
    if (ref.startsWith('TODO-')) max = Math.max(max, Number(ref.slice(5)));
  }
  return max + 1;
}

function nextTaskId(feature, kind) {
  let max = 0;
  for (const t of feature.tasks) {
    const m = t.id.match(new RegExp(`-${kind}(\\d+)$`));
    if (m) max = Math.max(max, Number(m[1]));
  }
  return `${feature.id}-${kind}${max + 1}`;
}

/**
 * A rank that lands immediately after `afterId` in the queue, by midpoint.
 * Returns null when the neighbours are adjacent — the caller reports that as
 * "no gap left here, run --renumber", which is the honest answer. Silently
 * picking a tie would be worse: a tie says "order does not matter", and the
 * caller just said it does.
 */
function rankAfter(flows, afterId) {
  const rows = queueRows(flows).filter((r) => r.rank !== null);
  const i = rows.findIndex((r) => r.t.id === afterId);
  if (i === -1) return { error: `${afterId} is not an open, ranked task` };
  const lo = rows[i].rank;
  const hi = rows[i + 1]?.rank ?? lo + 200;
  if (hi - lo < 2) {
    return { error: `no gap between rank ${lo} (${afterId}) and ${hi} — run \`${SCRIPT_REL} --renumber --apply\` to respace, then retry` };
  }
  return { rank: Math.floor((lo + hi) / 2) };
}

function newTask(flows, argv) {
  const featureId = argv['new-task'];
  const feature = flows.flatMap((f) => f.features).find((f) => f.id === featureId);
  if (!feature) {
    console.error(`❌ no feature \`${featureId}\` — features are '## ${cfg.idPrefix}01.2 — Title' headings in ${REL}/flows/`);
    process.exit(2);
  }
  const kind = argv.design ? 'D' : 'I';
  const id = nextTaskId(feature, kind);
  const todo = `TODO-${nextTodo(flows)}`;
  const owner = argv.owner ?? cfg.defaultOwner;

  let rank = argv.rank ?? null;
  if (argv.after) {
    const r = rankAfter(flows, argv.after);
    if (r.error) { console.error(`❌ ${r.error}`); process.exit(2); }
    rank = String(r.rank);
  }

  const parts = [`- [ ] \`${id}\``, `**${todo}**`];
  if (rank) parts.push(`**Rank:** ${rank}`);
  if (owner) parts.push(`**Owner:** ${owner}`);
  parts.push(`${argv.title ?? 'TITLE — what is wrong, and how you know'} — ⬜`);
  const line = parts[0] + ' ' + parts.slice(1).join(' · ');

  // What "no inline rank" actually means depends on the parents: a feature or
  // flow rank is inherited, and saying "unranked backlog" when the task will
  // in fact land at the feature's rank would be a lie the caller then acts on.
  const inherited = feature.rank ?? feature.flow?.rank ?? null;
  const rankNote = rank
    ? ''
    : inherited
      ? `\n(no inline rank: it inherits ${inherited} from ${feature.rank ? feature.id : feature.flow.id} — pass --rank <n> or --after <taskId> to override)`
      : `\n(no rank: it will sit in the unranked backlog — pass --rank <n> or --after <taskId> to give it a place)`;

  if (!argv.apply) {
    console.log(line);
    console.error(
      `\n(not written — add --apply to insert it at the end of ${feature.id}'s ### ${kind === 'D' ? 'Design' : 'Implementation'} section)` +
        rankNote,
    );
    return;
  }

  const file = join(ROOT, feature.flow.file);
  const lines = readFileSync(file, 'utf8').split(/\r?\n/);
  const sectionName = kind === 'D' ? 'Design' : 'Implementation';
  const headLine = feature[`${sectionName.toLowerCase()}Line`];
  if (!headLine) {
    console.error(`❌ ${feature.id} has no '### ${sectionName}' heading — add one first`);
    process.exit(2);
  }
  // Insert after the section's last task line, which is the last consecutive
  // `- [ ]`/`- [x]` line following the heading.
  let i = headLine; // 0-based index of the line AFTER the heading
  let last = headLine;
  while (i < lines.length && !/^#{1,3}\s/.test(lines[i])) {
    if (RE.task.test(lines[i])) last = i + 1;
    i++;
  }
  lines.splice(last, 0, line);
  writeFileSync(file, lines.join('\n'));
  console.log(`✅ ${feature.flow.file}:${last + 1}  ${id} (${todo})`);
  console.log(`   run \`${SCRIPT_REL} --write\` to refresh MASTER.md + QUEUE.md`);
}

// ---- --renumber ------------------------------------------------------------
// Safe precisely because ranks are UNCITED. Every rank value in the tree is
// remapped onto 100, 200, 300 … in sorted order — a monotone remap, so every
// relative comparison, every tie and the whole inheritance structure survive
// unchanged, and the gaps come back.

function renumber(flows, apply) {
  const holders = [];
  for (const fl of flows) {
    if (fl.rank) holders.push({ file: fl.file, line: fl.rankLine, rank: Number(fl.rank), what: `flow ${fl.id}` });
    for (const f of fl.features) {
      if (f.rank) holders.push({ file: fl.file, line: f.rankLine, rank: Number(f.rank), what: `feature ${f.id}` });
    }
    for (const t of fl.tasks) {
      if (t.rank) holders.push({ file: fl.file, line: t.line, rank: Number(t.rank), what: `task ${t.id}`, inline: true });
    }
  }
  if (!holders.length) { console.log('nothing to renumber — no ranks are set'); return; }

  const distinct = [...new Set(holders.map((h) => h.rank))].sort((a, b) => a - b);
  if (distinct.length * 100 > 9999) {
    console.error(`❌ ${distinct.length} distinct ranks × 100 exceeds the 9999 ceiling — widen the range or collapse some ties first`);
    process.exit(2);
  }
  const map = new Map(distinct.map((r, i) => [r, (i + 1) * 100]));

  const byFile = new Map();
  for (const h of holders) {
    if (!byFile.has(h.file)) byFile.set(h.file, []);
    byFile.get(h.file).push(h);
  }

  let changed = 0;
  for (const [file, hs] of byFile) {
    const path = join(ROOT, file);
    const lines = readFileSync(path, 'utf8').split(/\r?\n/);
    for (const h of hs) {
      const to = map.get(h.rank);
      if (to === h.rank) continue;
      const i = h.line - 1;
      const before = lines[i];
      lines[i] = h.inline
        ? before.replace(/(\*\*Rank:\*\*\s*)\d+/, `$1${to}`)
        : before.replace(/^(-\s+\*\*Rank:\*\*\s*)\d+/, `$1${to}`);
      if (lines[i] === before) { err(`${file}:${h.line}: could not rewrite the rank for ${h.what}`); continue; }
      changed++;
      if (!apply) console.log(`${file}:${h.line}  ${h.what}: ${h.rank} → ${to}`);
    }
    if (apply) writeFileSync(path, lines.join('\n'));
  }
  console.log(
    apply
      ? `✅ respaced ${changed} rank(s) across ${byFile.size} file(s) — run \`${SCRIPT_REL} --write\` to refresh QUEUE.md`
      : `\n${changed} rank(s) would change. Re-run with --apply to write them.`,
  );
}

// ---- main ------------------------------------------------------------------

function parseArgs(argv) {
  const out = { _: [] };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (!a.startsWith('--')) { out._.push(a); continue; }
    const key = a.slice(2);
    const next = argv[i + 1];
    const takesValue = ['commit-msg', 'new-task', 'after', 'rank', 'owner', 'title', 'config', 'next'];
    if (takesValue.includes(key) && next && !next.startsWith('--')) { out[key] = next; i++; }
    else out[key] = true;
  }
  return out;
}

const argv = parseArgs(process.argv.slice(2));
const quiet = argv.json || argv.next !== undefined || argv['new-task'] || argv.renumber;
const flows = loadFlows();
for (const fl of flows) validateFlow(fl);

if (argv['commit-msg']) {
  if (argv['commit-msg'] === true) { console.error('usage: --commit-msg <path>'); process.exit(2); }
  commitMsgMode(argv['commit-msg'], flows);
} else if (argv['new-task']) {
  if (errors.length) {
    console.error('❌ fix the tracking errors first — a new id allocated against a broken tree may collide:');
    for (const e of errors) console.error(`   - ${e}`);
    process.exit(1);
  }
  newTask(flows, argv);
  process.exit(0);
} else if (argv.renumber) {
  renumber(flows, !!argv.apply);
  process.exit(errors.length ? 1 : 0);
} else if (argv.json) {
  const rows = queueRows(flows);
  console.log(JSON.stringify({
    ok: errors.length === 0,
    errors,
    warnings,
    nextTodo: `TODO-${nextTodo(flows)}`,
    flows: flows.map((f) => ({
      id: f.id, title: f.title, file: f.file, spec: f.spec, phase: f.phase,
      status: f.status?.name ?? null,
      done: f.tasks.filter((t) => t.status === 'done').length,
      total: f.tasks.length,
    })),
    queue: rows.map(({ t, rank }) => ({
      id: t.id, todo: t.todo, rank, status: t.status,
      owner: t.owner ?? t.feature?.owner ?? null,
      feature: t.feature?.id ?? null, at: t.at, label: taskLabel(t),
      blockedReason: t.blockedReason,
    })),
  }, null, 2));
  process.exit(errors.length ? 1 : 0);
} else if (argv.write) {
  writeBlock(MASTER, 'ROLLUP', masterBlock(flows));
  writeBlock(QUEUE, 'QUEUE', queueTable(flows));
  checkPromises(flows);
} else {
  checkBlockFresh(MASTER, 'ROLLUP', masterBlock(flows), 'rollup');
  checkBlockFresh(QUEUE, 'QUEUE', queueTable(flows), 'queue');
  checkPromises(flows);
}

const cov = coverage(flows);
if (cov && cov.missing.length && !argv['commit-msg']) {
  warn(`uncovered required spec sections: ${cov.missing.map((s) => '§' + s).join(', ')}`);
}

if (!argv['commit-msg']) {
  if (ownerless.length) {
    const ids = [...new Set(ownerless.map((t) => t.feature.id.split('.')[0]))].sort();
    const msg =
      `${ownerless.length} started-or-finished task(s) have no owner, across ${ids.length} flow(s): ${ids.join(', ')}. ` +
      `Add '- **Owner:** <name>' under the feature heading, or '**Owner:** <name>' inline on the task.`;
    (cfg.strict.owner ? err : warn)(msg);
  }
  if (unranked.length) {
    const ids = [...new Set(unranked.map((t) => t.flow?.id).filter(Boolean))].sort();
    const msg =
      `${unranked.length} open task(s) have no rank, across ${ids.length} flow(s): ${ids.join(', ')}. ` +
      `They sort last in ${REL}/QUEUE.md. Add '- **Rank:** <n>' under the feature heading, or '**Rank:** <n>' inline on the task.`;
    (cfg.strict.rank ? err : warn)(msg);
  }
}

if (!quiet) for (const w of warnings) console.warn(`⚠️  ${w}`);
if (errors.length) {
  console.error(`\n❌ tracking validation failed with ${errors.length} error(s):`);
  for (const e of errors) console.error(`   - ${e}`);
  process.exit(1);
}

const ranked = queueRows(flows).filter((r) => r.t.status !== 'blocked' && r.rank !== null);

if (argv.next !== undefined) {
  const n = Number(argv.next === true ? 5 : argv.next) || 5;
  for (const r of ranked.slice(0, n)) {
    console.log(`${String(r.rank).padStart(5)}  ${EMOJI[r.t.status]}  ${r.t.id.padEnd(12)} ${taskLabel(r.t)}`);
  }
  process.exit(0);
}

console.log(
  `✅ tracking OK — ${flows.length} flow(s), ` +
    `${flows.reduce((n, f) => n + f.features.length, 0)} feature(s), ` +
    `${flows.reduce((n, f) => n + f.tasks.length, 0)} task(s).`,
);

// Print the head of the queue on every run. A hand-maintained order rots
// because nobody opens the file it lives in; this line runs on every pre-commit
// hook and every CI job, which is the highest-frequency feedback loop there is —
// so a wrong order gets seen rather than filed.
if (!argv['commit-msg'] && ranked.length) {
  console.log(
    `   next up: ${ranked.slice(0, 3).map((r) => `${r.t.id} (${r.rank})`).join(' · ')} — full queue: ${REL}/QUEUE.md`,
  );
}
